/**
 * Offline-first local storage abstraction.
 * Purely local, zero network requirements.
 */

export interface ILocalStorage {
  getItem(key: string): Promise<string | null>;
  setItem(key: string, value: string): Promise<void>;
  removeItem(key: string): Promise<void>;
  clear(): Promise<void>;
}

// In-memory fallback / simple local cache implementation
class MemoryLocalStorage implements ILocalStorage {
  private store = new Map<string, string>();

  async getItem(key: string): Promise<string | null> {
    return this.store.get(key) ?? null;
  }

  async setItem(key: string, value: string): Promise<void> {
    this.store.set(key, value);
  }

  async removeItem(key: string): Promise<void> {
    this.store.delete(key);
  }

  async clear(): Promise<void> {
    this.store.clear();
  }
}

export const offlineStorage: ILocalStorage = new MemoryLocalStorage();

